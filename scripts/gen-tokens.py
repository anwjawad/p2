"""Generate the colour ramps of the design system (web/css/tokens.css).

Every Tailwind colour family used by the app is mapped onto one of six ramps.
Each ramp has a light and a dark variant built in OKLCH so steps are
perceptually even; the dark ramp is mirrored (50 = darkest) so existing
pairs like `bg-slate-50 text-slate-800` keep their contrast in dark mode.

    python scripts/gen-tokens.py
"""
import math, pathlib

STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

# name: (hue, max chroma, light L ramp, dark L ramp)
NEUTRAL_L = [.978, .955, .905, .82, .52, .47, .42, .36, .29, .215, .17]
NEUTRAL_D = [.175, .222, .30, .38, .70, .745, .80, .86, .915, .955, .975]
COLOR_L = [.972, .935, .875, .79, .68, .59, .515, .45, .385, .32, .26]
COLOR_D = [.235, .285, .345, .42, .55, .66, .75, .82, .88, .93, .96]

RAMPS = {
    'neutral':  (165, .014, NEUTRAL_L, NEUTRAL_D),
    'accent':   (178, .095, COLOR_L, COLOR_D),   # spruce
    'plum':     (305, .085, COLOR_L, COLOR_D),   # AI / plan
    'critical': (25,  .175, COLOR_L, COLOR_D),   # red
    'warning':  (68,  .150, COLOR_L, COLOR_D),   # marigold / amber
    'positive': (152, .120, COLOR_L, COLOR_D),   # green
}


def oklch_to_srgb(L, C, h):
    a, b = C * math.cos(math.radians(h)), C * math.sin(math.radians(h))
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s

    def enc(x):
        return 12.92 * x if x <= 0.0031308 else 1.055 * (x ** (1 / 2.4)) - 0.055
    return [enc(v) for v in (r, g, bl)]


def in_gamut(rgb):
    return all(-1e-4 <= v <= 1 + 1e-4 for v in rgb)


def color(L, maxC, h):
    # chroma peaks mid-ramp and tapers at the extremes
    c = maxC * max(0.12, 1 - abs(L - 0.58) / 0.5) ** 0.9
    while c > 0 and not in_gamut(oklch_to_srgb(L, c, h)):
        c -= 0.002
    r, g, b = (round(max(0, min(1, v)) * 255) for v in oklch_to_srgb(L, max(c, 0), h))
    return f'{r} {g} {b}'


def block(mode):
    out = []
    for name, (h, c, lr, dr) in RAMPS.items():
        ramp = lr if mode == 'light' else dr
        for step, L in zip(STEPS, ramp):
            out.append(f'  --{name}-{step}: {color(L, c, h)};')
    return '\n'.join(out)


css = f"""/* GENERATED by scripts/gen-tokens.py — do not edit by hand. */
:root {{
{block('light')}
  --white: 255 255 255;
}}
:root[data-theme="dark"] {{
{block('dark')}
  --white: {color(.215, .012, 165)};
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{block('dark')}
  --white: {color(.215, .012, 165)};
  }}
}}
"""
path = pathlib.Path(__file__).resolve().parents[1] / 'web' / 'css' / 'tokens.css'
path.write_text(css, encoding='utf-8')
print('wrote', path)
